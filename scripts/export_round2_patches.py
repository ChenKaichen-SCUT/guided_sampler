#!/usr/bin/env python3
from common import *
import difflib
def main():
 out=ROOT/'patches/round2_a';out.mkdir(parents=True,exist_ok=True);source=ROOT/'worktrees/round2_release';files={}
 for part in ('HighDiv','z3'):
  lines=[]
  for base in ('src',):
   for p in sorted((source/part/base).rglob('*')):
    if not p.is_file() or p.suffix not in ('.cpp','.h','.hpp','.inc'):continue
    rel=p.relative_to(source);old=UP/rel
    if not old.exists() and str(rel) not in {'z3/src/util/a_shared.hpp','z3/src/util/a_state.h','z3/src/smt/a_context.inc','z3/src/smt/a_internal_view.h','z3/src/api/z3_a_guidance.h'}:continue
    if old.exists() and old.read_bytes()==p.read_bytes():continue
    files[str(rel)]={'new_sha256':digest(p),'upstream_sha256':digest(old) if old.exists() else None}
    lines.extend(difflib.unified_diff(old.read_text().splitlines(True) if old.exists() else [],p.read_text().splitlines(True),fromfile='a/'+str(rel) if old.exists() else '/dev/null',tofile='b/'+str(rel)))
  (out/(part+'.patch')).write_text(''.join(lines))
 write(out/'files.json',files);print('Exported',len(files),'modified/new source files; toolchain-specific makefile is generated by build script')
if __name__=='__main__':main()
